/**
 * Helper to fetch translation string
 * @param {string} key
 * @param {string} [fallback]
 * @returns {string}
 */
window.t = function(key, fallback = '') {
  const currentLang = window.AZOLLA_CURRENT_LANG || 'ar';
  const langObj = window.AZOLLA_TRANSLATIONS && window.AZOLLA_TRANSLATIONS[currentLang];
  if (langObj && langObj[key] !== undefined) {
    return langObj[key];
  }
  // Fallback to Arabic
  const arObj = window.AZOLLA_TRANSLATIONS && window.AZOLLA_TRANSLATIONS['ar'];
  if (arObj && arObj[key] !== undefined) {
    return arObj[key];
  }
  return fallback || key;
};
